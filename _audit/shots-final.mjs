import { setTimeout as sleep } from "node:timers/promises";
import fs from "node:fs";
const OUT = "_audit/shots";
fs.mkdirSync(OUT, { recursive: true });
const list = await (await fetch("http://127.0.0.1:9222/json/list")).json();
const page = list.find((t) => t.type === "page");
const ws = new WebSocket(page.webSocketDebuggerUrl);
let id = 0;
const pending = new Map();
ws.addEventListener("message", (ev) => { const m = JSON.parse(ev.data); if (m.id && pending.has(m.id)) { pending.get(m.id)(m); pending.delete(m.id); } });
await new Promise((r) => ws.addEventListener("open", r));
const send = (method, params = {}) => new Promise((res, rej) => { const i = ++id; pending.set(i, (m) => (m.error ? rej(new Error(m.error.message)) : res(m.result))); ws.send(JSON.stringify({ id: i, method, params })); });
const evaluate = async (e) => (await send("Runtime.evaluate", { expression: e, returnByValue: true, awaitPromise: true })).result.value;
const shot = async (n) => { const r = await send("Page.captureScreenshot", { format: "png", fromSurface: true }); fs.writeFileSync(`${OUT}/${n}.png`, Buffer.from(r.data, "base64")); };
const theme = process.env.AUDIT_THEME || "light";
await send("Page.enable");
await send("Emulation.setDeviceMetricsOverride", { width: 1080, height: 680, deviceScaleFactor: 1, mobile: false });
await send("Page.navigate", { url: `http://127.0.0.1:5173/?theme=${theme}&v=${Date.now()}` });
for (let i = 0; i < 60; i++) { await sleep(250); if (await evaluate(`document.querySelectorAll('.nav-item').length >= 8 && !document.querySelector('.boot-splash')`)) break; }
await sleep(400);
console.log("header version:", await evaluate(`(document.querySelector('.brand-ver, .app-ver, header') || {}).textContent`));
await evaluate(`document.querySelectorAll('.nav-item')[1].click()`); await sleep(700); await shot(`fix2-${theme}-proxies`);
await evaluate(`document.querySelectorAll('.nav-item')[6].click()`); await sleep(800); await shot(`fix2-${theme}-test`);
await evaluate(`document.querySelectorAll('.nav-item')[7].click()`); await sleep(500);
await evaluate(`(() => { const b=[...document.querySelectorAll('.s-nav button')].find(e=>(e.textContent||'').trim()==='关于'); b && b.click(); })()`);
await sleep(800);
console.log("about version:", await evaluate(`(() => { const t=document.querySelector('.pane'); return (t.textContent||'').replace(/\\s+/g,' ').slice(0, 220); })()`));
await shot(`fix2-${theme}-about`);
ws.close();
